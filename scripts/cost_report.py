"""Week 11, mentor checks #2 and #3: where a request's time and tokens go, step by step, and what a request costs.

The request log keeps a record per STEP (embedding the question, searching, asking the model), with the model step's time
split into time at the provider and time spent waiting for the rate limit. This adds them up across many requests, so you can say which
step to fix instead of "it is slow". Tokens come first, because the provider reports them. Dollars appear only from prices YOU state
(--price-in and --price-out, dollars per million tokens), with the price and its source printed under every figure, because a price is
an assumption. A request whose provider reported no tokens is left out of the token and dollar figures and counted, never averaged in
as zero.

Run:
    python scripts/cost_report.py                                      # the app's own request log
    python scripts/cost_report.py --log data/measure/w11/after/traces.jsonl --skip-cold
    python scripts/cost_report.py --price-in 0.10 --price-out 0.40 --price-source "provider list, 2026-10"
    python scripts/cost_report.py --compare data/measure/w11/before/traces.jsonl data/measure/w11/after/traces.jsonl
    python scripts/cost_report.py --show w11                           # a saved measurement, evals/results/cost-w11.json

A synthetic log (the support drill's) is refused unless you pass --include-synthetic: its tokens and times are invented.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app import pricing                                          # noqa: E402
from app.config import BASE_DIR                                  # noqa: E402
from app.console import display_path, make_output_safe           # noqa: E402
from evals import cost_run, costreport, logsearch                # noqa: E402


def load_logs(paths, include_synthetic):
    """The records of these logs, or (None, reason) when there are none or they are synthetic and that was not asked for."""
    try:
        records, skipped, took = logsearch.load(paths)
    except ValueError as exc:
        return None, str(exc)
    if not records:
        return None, "No log lines found in: " + ", ".join(display_path(path, BASE_DIR) for path in paths)
    if any(record["synthetic"] for record in records) and not include_synthetic:
        return None, ("these records were generated by scripts/make_drill.py for practice: their tokens, times and costs are invented, so a cost report "
                      "of them would be a number about nothing. Pass --include-synthetic to read them anyway.")
    return records, None


def show_measurement(label, args):
    """A saved measurement as a table per arm, with dollars at the stated prices."""
    try:
        results = cost_run.load_aggregate(label)
    except FileNotFoundError as exc:
        print(f"Error: {exc}")
        if cost_run.aggregate_exists(label):                 # a stopped run kept beside an older complete one (or the like)
            print(f"The measurement is incomplete (evals/results/cost-{label}.incomplete.json): carry it on with python scripts/measure_cost.py --label {label} --resume.")
        return 1
    except (OSError, ValueError) as exc:
        print(f"Error: {exc}")
        return 1
    print("\n".join(cost_run.format_summary(results)))
    priced = pricing.is_priced(logsearch.stated_price(args.price_in), logsearch.stated_price(args.price_out))
    if not priced:
        print(f"\n{logsearch.no_dollars_reason(args.price_in, args.price_out)}, so no dollars are shown (pass --price-in and --price-out above 0, and --price-source)")
        return 0
    if results["meta"].get("dry_run"):
        print("\nno dollars for a dry run: its tokens come from a scripted provider")
        return 0
    print(f"\ndollars per request at stated prices ({pricing.describe_prices(args.price_in or 0.0, args.price_out or 0.0)}; from: {args.price_source or '(source not stated)'}):")
    for arm in results["meta"]["arms"]:
        rows = [r for r in results["rows"] if r["arm"] == arm["name"] and r["status"] != "error" and r["tokens_known"]]
        costs = [pricing.cost_of(r["prompt_tokens"], r["completion_tokens"], args.price_in or 0.0, args.price_out or 0.0) for r in rows]
        mean = f"${sum(costs) / len(costs):.6f}" if costs else "no data"
        print(f"  {arm['name']:<14}{mean:>14}   (n {len(costs)} priced of {sum(1 for r in results['rows'] if r['arm'] == arm['name'])})")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description="Where a request's time and tokens go, step by step, and what it costs.")
    parser.add_argument("--log", action="append", metavar="PATH", help="read this request log (repeatable); default: the app's traces log")
    parser.add_argument("--compare", nargs=2, metavar=("LOG_A", "LOG_B"), help="two logs of the same questions side by side (refused if the models differ)")
    parser.add_argument("--show", metavar="LABEL", help="a saved measurement (evals/results/cost-LABEL.json) with dollars at the stated prices")
    parser.add_argument("--price-in", type=float, metavar="USD", help="dollars per million input tokens (an assumption you state)")
    parser.add_argument("--price-out", type=float, metavar="USD", help="dollars per million output tokens (an assumption you state)")
    parser.add_argument("--price-source", metavar="TEXT", help="where the prices come from, printed under every dollar figure")
    parser.add_argument("--skip-cold", action="store_true", help="leave out the first step of each kind in a process (one-time start-up costs)")
    parser.add_argument("--include-synthetic", action="store_true", help="read a synthetic log (the drill's) anyway")
    args = parser.parse_args(argv)
    make_output_safe()

    for name, value in (("--price-in", args.price_in), ("--price-out", args.price_out)):
        if value is not None and not 0 <= value < float("inf"):
            print(f"Error: {name} must be 0 or more dollars per million tokens.")
            return 1
    if args.show:
        return show_measurement(args.show, args)

    if args.compare:
        loaded = [load_logs([path], args.include_synthetic) for path in args.compare]
        for records, reason in loaded:
            if records is None:
                print(f"Error: {reason}")
                return 1
        shown = []
        for records, _ in loaded:
            for line in logsearch.banners(records):
                if line not in shown:                          # once, not once per log
                    shown.append(line)
                    print(line)
        result = costreport.compare(loaded[0][0], loaded[1][0], args.price_in, args.price_out)
        print("\n".join(costreport.compare_lines(result, os.path.basename(os.path.dirname(args.compare[0])) or args.compare[0],
                                                os.path.basename(os.path.dirname(args.compare[1])) or args.compare[1],
                                                args.price_source, args.price_in, args.price_out)))
        return 1 if result["refused"] else 0

    paths = args.log or logsearch.default_paths()[:1]
    records, reason = load_logs(paths, args.include_synthetic)
    if records is None:
        print(f"Error: {reason}")
        return 1
    print("reading " + ", ".join(display_path(path, BASE_DIR) for path in paths) + f": {len(records)} records")
    for line in logsearch.banners(records):
        print(line)
    print()
    print("\n".join(costreport.request_lines(costreport.per_request(records, args.price_in, args.price_out), args.price_source, args.price_in, args.price_out)))
    print("\nstep by step (times in milliseconds):\n")
    print("\n".join(costreport.step_lines(costreport.per_step(records, args.skip_cold))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
